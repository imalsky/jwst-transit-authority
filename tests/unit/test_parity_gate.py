def test_config_mismatch_fails_but_an_implicit_default_does_not(gate, passing):
    """A real disagreement fails; an unset-because-derived key does not.

    Our registry omits `disperser` for MIRI LRS (the mode admits only the p750l
    prism and the engine derives it), while PandExo reports "p750l". That is a
    representation difference, not a configuration difference.
    """
    s = copy.deepcopy(passing)
    s["stars"]["w39_like"]["modes"][0]["config_ours"]["disperser"] = None
    assert not [p for p in gate["validate"](s) if "disperser" in p]

    s["stars"]["w39_like"]["modes"][0]["config_ours"]["readout"] = "FASTR1"
    problems = gate["validate"](s)
    assert any("submitted readout differs" in p for p in problems), problems


def test_faint_star_group_rounding_is_allowed(gate, passing):
    """REPORT.md claims "~1% relative (up to 5 groups absolute)" on the faint
    star. At ngroup ~500 a 5-group rounding difference is 1.006%, so a pure 1%
    test would fail the real, matched artifact."""
    rel = gate["REQUIRED_PANDEIA_RELEASE"]
    star = copy.deepcopy(passing["stars"]["w39_like"])
    star["modes"] = [_ok_row(k) for k in gate["REQUIRED_UNSATURATED_MODES"]]
    star["modes"][0].update(ngroup_ours=497, ngroup_pandexo=492)   # 1.006%
    star["modes"][1].update(ngroup_ours=195, ngroup_pandexo=193)   # 1.03%
    s = {"stars": {"faint_k": star}}
    assert not [p for p in gate["validate"](s) if "ngroup" in p]

    # a real optimizer divergence still fails
    star["modes"][2].update(ngroup_ours=500, ngroup_pandexo=400)
    assert any("ngroup" in p for p in gate["validate"](s))


def test_bright_star_group_difference_of_two_fails(gate, passing):
    s = copy.deepcopy(passing)
    s["stars"]["w39_like"]["modes"][0].update(ngroup_ours=20,
                                              ngroup_pandexo=18)
    problems = gate["validate"](s)
    assert any("ngroup 20 vs 18" in p for p in problems), problems


def test_committed_artifact_does_not_pass_the_gate(gate):
    """Guard against the committed artifact being mistaken for a current pass.

    It must keep failing until it is regenerated on the supported release with
    worker v7. If this ever starts passing without a regeneration, something
    loosened the gate.
    """
    import json

    path = (PARITY.parents[1] / "outputs" / "parity_summary.json")
    if not path.is_file():                              # pragma: no cover
        pytest.skip("committed parity_summary.json not present")
    problems = gate["validate"](json.loads(path.read_text()))
    assert problems, "the stale 2026.2/worker-v5 artifact must not pass"
    joined = " ".join(problems)
    assert "worker_version=5" in joined
    assert "2026.2" in joined
